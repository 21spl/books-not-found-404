CREATE TABLE inventory_reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventory_reservation_purchase
        FOREIGN KEY (purchase_id)
        REFERENCES purchase(id),

    CONSTRAINT fk_inventory_reservation_book
        FOREIGN KEY (book_id)
        REFERENCES books(id),

    CONSTRAINT chk_inventory_reservation_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_inventory_reservation_status
        CHECK (status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED')),

    CONSTRAINT uk_inventory_reservation_purchase_book
        UNIQUE (purchase_id, book_id)
);

-- Helps find reservations belonging to a purchase.
CREATE INDEX idx_inventory_reservation_purchase
    ON inventory_reservation(purchase_id);

-- Helps background jobs find reservations awaiting expiry.
CREATE INDEX idx_inventory_reservation_active_expiry
    ON inventory_reservation(expires_at)
    WHERE status = 'ACTIVE';